import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Build the Windows SEA from our existing server rather than maintaining a separate API.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dist');
fs.mkdirSync(out, {recursive:true});
const read = name => fs.readFileSync(path.join(root, name),'utf8');
const imports = /^import\s+.*?\s+from\s+['"][^'"]+['"];?\s*$/gm;
const dbRaw = read('server/db.js');
const serverRaw = read('server/index.js');
if (!dbRaw.includes("import { DatabaseSync } from 'node:sqlite'") || !serverRaw.includes('export const server=http.createServer(handler);')) throw new Error('Review desktop adapter: source structure changed');
const db = dbRaw.replace(imports,'').replaceAll('export const ','const ').replaceAll('export function ','function ');
let api = serverRaw.replace(imports,'')
  .replace("const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');","const ROOT = path.resolve(__dirname,'..');")
  .replace('export const server=http.createServer(handler);','const server=http.createServer(handler);')
  .replace(/if\(process\.argv\[1\]&&path\.resolve\(process\.argv\[1\]\)===fileURLToPath\(import\.meta\.url\)\)server\.listen\(.*?\);\s*$/s,'');
if (api.includes('import.meta') || api.includes('fileURLToPath')) throw new Error('Unconverted module import');
if (!api.includes('const data=fs.readFileSync(local);')) throw new Error('Server static path changed');
api = api.replace('const data=fs.readFileSync(local);',"const data=bundled?Buffer.from(sea.getAsset(requested.slice(1))):fs.readFileSync(local);");
const header = [
  "// Generated by tools/build-desktop.mjs; do not edit manually.",
  "'use strict';",
  "const http=require('node:http');",
  "const fs=require('node:fs');",
  "const path=require('node:path');",
  "const crypto=require('node:crypto');",
  "const {DatabaseSync}=require('node:sqlite');",
  "const os=require('node:os');",
  "const sea=require('node:sea');",
  "const {execFile}=require('node:child_process');",
  "const bundled=sea.isSea();",
  "if(!process.env.DB_PATH)process.env.DB_PATH=path.join(process.env.APPDATA||path.join(os.homedir(),'AppData','Roaming'),'DevShow','data','devshow.sqlite');",
  "if(!process.env.PORT)process.env.PORT='3217';"
].join('\n');
const footer = [
  "const listenPort=Number(process.env.PORT);",
  "if(process.argv.includes('--self-test')){",
  " const value=one('SELECT COUNT(*) AS count FROM users');",
  " if(bundled&&!sea.getAsset('index.html','utf8').includes('DevShow'))throw Error('Missing embedded site');",
  " console.log('DevShow desktop self-test passed; users='+value.count);db.close();",
  "}else{",
  " server.on('error',e=>{console.error('DevShow server error:',e.message);process.exitCode=1;});",
  " server.listen(listenPort,'127.0.0.1',()=>{",
  "  const url='http://127.0.0.1:'+listenPort;",
  "  console.log('DevShow Desktop v2.1 | '+url);",
  "  console.log('Database: '+process.env.DB_PATH);",
  "  console.log('Keep this window open while using DevShow.');",
  "  if(process.platform==='win32')execFile('rundll32.exe',['url.dll,FileProtocolHandler',url],{windowsHide:true},err=>{if(err)console.error('Open '+url+' in your browser.');});",
  " });",
  "}"
].join('\n');
fs.writeFileSync(path.join(out,'desktop-entry.cjs'),header+'\n'+db+'\n'+api+'\n'+footer+'\n');
const files=['index.html','config.js','styles.css','assets/favicon.svg','src/app.js','src/cloud.js','src/data.js'];
fs.writeFileSync(path.join(out,'sea-config.json'),JSON.stringify({main:'dist/desktop-entry.cjs',output:'dist/DevShow-Desktop.exe',disableExperimentalSEAWarning:true,assets:Object.fromEntries(files.map(f=>[f,f]))},null,2)+'\n');
console.log('Prepared single executable source and '+files.length+' embedded frontend files.');
