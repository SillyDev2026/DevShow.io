import assert from 'node:assert/strict';
const DOM = new Map();
for (const id of ['app','content-slot','aside-slot','breadcrumb','modal-slot','toast-region']) DOM.set('#'+id, {innerHTML:'',textContent:'',style:{},focus(){}});
const listeners = {};
globalThis.requestAnimationFrame = (fn) => fn();
globalThis.document = { documentElement:{dataset:{}},body:{style:{}},querySelector(selector){return DOM.get(selector) || {innerHTML:'',classList:{add(){}},focus(){}}},addEventListener(name,fn){listeners[name]=fn} };
globalThis.window = {addEventListener(){},scrollTo(){}};
globalThis.location = {hash:'',href:'http://example.com/'};
globalThis.history = {replaceState(_a,_b,url){location.hash=url}};
globalThis.localStorage = {store:{},getItem(k){return this.store[k]??null},setItem(k,v){this.store[k]=v},removeItem(k){delete this.store[k]}};
await import('../src/app.js');
const click = (action,extra={}) => listeners.click({target:{closest(){return {dataset:{action,...extra}}}}});
assert.ok(DOM.get('#app').innerHTML.includes('Build something.'));
assert.equal((DOM.get('#app').innerHTML.match(/class="project-card"/g)||[]).length,12);
click('like',{id:'p1'});
assert.deepEqual(JSON.parse(localStorage.store['devshow-v1-local-demo']).liked,['p1']);
click('save',{id:'p1'});
assert.deepEqual(JSON.parse(localStorage.store['devshow-v1-local-demo']).saved,['p1']);
click('category',{category:'Roblox'});
assert.equal((DOM.get('#content-slot').innerHTML.match(/class="project-card"/g)||[]).length,2);
click('nav',{page:'leaderboard'});
assert.ok(DOM.get('#app').innerHTML.includes('The leaderboard'));
click('profile',{id:'silly'});
assert.ok(DOM.get('#app').innerHTML.includes('SillyDev'));
click('follow',{id:'silly'});
assert.deepEqual(JSON.parse(localStorage.store['devshow-v1-local-demo']).following,['silly']);
click('new');
assert.ok(DOM.get('#modal-slot').innerHTML.includes('create-form'));
console.log('PASS initial render, cards, likes, bookmarks, filters, leaderboard, profiles, follows, publish modal');
